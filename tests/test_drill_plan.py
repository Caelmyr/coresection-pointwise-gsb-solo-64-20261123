"""End-to-end checks for the 16 mm core drill planning and audit workflow.

Run from the repository root:  python3 tests/test_drill_plan.py
The script creates its own empty data directory and never touches uploaded
material; every fixture image is generated by the demo machinery.
"""
import io
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from PIL import Image  # noqa: E402

from coresection.demo import SERIES, training_specimen  # noqa: E402
from coresection.drill import (  # noqa: E402
    CORE_DIAMETER_MM,
    LAYER_BRITTLE,
    LAYER_MATRIX,
    LAYER_UNREADABLE,
    LAYER_VEIN,
    audit_drill,
    plan_drill,
)
from coresection.model import InputError  # noqa: E402
from coresection.store import Store  # noqa: E402
from coresection.web import create_app  # noqa: E402


BRITTLE = [[[0.05, 0.05], [0.16, 0.05], [0.16, 0.16], [0.05, 0.16]]]
MATRIX = [[[0.30, 0.30], [0.70, 0.30], [0.70, 0.70], [0.30, 0.70]]]
VEIN = [[[0.46, 0.30], [0.50, 0.30], [0.50, 0.70], [0.46, 0.70]]]
CENTER_INSIDE = [0.50, 0.50]
CENTER_EDGE = [0.24, 0.50]


def layers():
    return {LAYER_BRITTLE: BRITTLE, LAYER_MATRIX: MATRIX, LAYER_VEIN: VEIN}


def plan_payload(centers, title="16 mm core trial"):
    return {"title": title, "layers": layers(), "centers": centers}


def main():
    with tempfile.TemporaryDirectory(prefix="coresection-drill-") as data_dir:
        store = Store(Path(data_dir))
        tile = store.seed_tiles("drill-test-v1", [training_specimen(store, SERIES[0])])[0]
        assert tile["width_mm"] == 112 and tile["height_mm"] == 84

        # --- Planning: the center inside matrix+vein must win -------------- #
        document, overlay = plan_drill(store, tile, plan_payload([CENTER_INSIDE, CENTER_EDGE]))
        assert document["core_diameter_mm"] == CORE_DIAMETER_MM
        assert document["chosen_center"] == CENTER_INSIDE
        assert document["alternate_center"] == CENTER_EDGE
        chosen = next(item for item in document["candidates"] if item["center"] == CENTER_INSIDE)
        alternate = next(item for item in document["candidates"] if item["center"] == CENTER_EDGE)
        assert chosen["feasible"] is True
        assert sum(chosen["overlap_pixels"].values()) == 0
        assert chosen["matrix_area_mm2_inside"] > alternate["matrix_area_mm2_inside"]
        assert chosen["vein_area_mm2_inside"] > 0
        assert chosen["clearance_mm"]["brittle_edge"] > 0
        # The footprint must be the physical 16 mm circle area (~201 mm²).
        assert 195 < chosen["footprint_area_mm2"] < 208, chosen["footprint_area_mm2"]
        assert document["advantage"], "the runner-up advantage must be explained in concrete terms"
        assert overlay.size == tuple(document["frame_extent"])
        print("plan metrics:", {
            "matrix_mm2": round(chosen["matrix_area_mm2_inside"], 2),
            "vein_mm2": round(chosen["vein_area_mm2_inside"], 2),
            "clearance": chosen["clearance_mm"],
        })

        # --- A circle that lands on brittle ground is rejected ------------- #
        bad = plan_payload([[0.10, 0.10], [0.11, 0.11]], "infeasible")
        try:
            plan_drill(store, tile, bad)
        except InputError as error:
            assert "full 16 mm circle clear" in str(error)
        else:
            raise AssertionError("overlapping the brittle edge should be rejected")

        # --- Missing physical calibration gives a clear error -------------- #
        uncalibrated = {**tile, "width_mm": None, "height_mm": None}
        try:
            plan_drill(store, uncalibrated, plan_payload([CENTER_INSIDE, CENTER_EDGE]))
        except InputError as error:
            assert "physical specimen" in str(error)
        else:
            raise AssertionError("mm planning without a scale must fail")

        # --- An explicitly marked unreadable patch blocks the circle ------- #
        # The patch covers the whole footprint of the only offered center.
        blocked_payload = {
            "title": "unreadable ground",
            "layers": {**layers(), LAYER_UNREADABLE: [[[0.32, 0.32], [0.68, 0.32], [0.68, 0.68], [0.32, 0.68]]]},
            "centers": [CENTER_INSIDE],
        }
        try:
            plan_drill(store, tile, blocked_payload)
        except InputError as error:
            assert "full 16 mm circle clear" in str(error)
        else:
            raise AssertionError("a circle over an unreadable patch must be rejected")

        # With a second clear center available, ranking falls back to it and
        # reports the blocked one as infeasible rather than failing the plan.
        fallback, _ = plan_drill(store, tile, {**blocked_payload, "centers": [CENTER_INSIDE, CENTER_EDGE]})
        assert fallback["chosen_center"] == CENTER_EDGE
        assert not fallback["candidates"][0]["feasible"] or not fallback["candidates"][1]["feasible"]

        # --- Post-drill audit against the same chosen circle --------------- #
        repeat_photo = next(item for item in tile["photos"] if item["role"] == "parallel")
        # Gap mostly follows the circle, deliberately offset so some material
        # stays uncut on one side and some rock is overcut on the other.
        gap = [[[0.46, 0.42], [0.585, 0.42], [0.585, 0.585], [0.46, 0.585]]]
        unreadable = [[[0.44, 0.47], [0.475, 0.47], [0.475, 0.54], [0.44, 0.54]]]
        audit_payload = {
            "photo_id": repeat_photo["id"],
            "layers": {**layers(), LAYER_UNREADABLE: unreadable},
            "gap": gap,
        }
        record, audit_image = audit_drill(store, tile, document, audit_payload)
        metrics = record["metrics"]
        assert metrics["uncut_inside_circle_mm2"] > 0, "offset gap must leave uncut material"
        assert metrics["overcut_outside_circle_mm2"] > 0, "offset gap must overcut outside the circle"
        assert metrics["indeterminate_boundary_mm2"] > 0, "unreadable junction must be separated out"
        decided = metrics["uncut_inside_circle_mm2"] + metrics["matched_mm2"]
        # Unreadable pixels must never be counted as uncut material.
        assert abs(decided + metrics["indeterminate_boundary_mm2"]
                   - metrics["circle_area_mm2"]) < 2.0, metrics
        assert audit_image.size == tuple(record["frame_extent"])
        print("audit metrics:", {key: round(value, 2) if isinstance(value, float) else value
                                 for key, value in metrics.items()})

        # --- Persistence and the Flask routes ------------------------------ #
        saved = store.save_drill_plan({
            **document,
            "specimen": {"id": tile["id"], "version": tile["version"], "name": tile["name"],
                         "body": None, "glaze": None, "firing": None, "batch": None,
                         "physical_mm": [tile["width_mm"], tile["height_mm"]]},
            "plan_overlay": store.blobs.put(_png(overlay)),
        })
        assert store.drill_plan(saved["id"])["title"] == saved["title"]
        assert [item["id"] for item in store.list_drill_plans(tile["id"])] == [saved["id"]]
        updated = store.update_drill_plan(saved["id"], {
            "audit": record, "audit_overlay": store.blobs.put(_png(audit_image)),
        })
        assert updated["audit"]["metrics"]["matched_mm2"] == metrics["matched_mm2"]

        app = create_app(data_dir)
        client = app.test_client()
        listing = client.get(f"/api/specimens/{tile['id']}/drill-plans")
        assert listing.status_code == 200 and len(listing.get_json()["items"]) == 1
        shown = client.get(f"/api/drill-plans/{saved['id']}")
        assert shown.status_code == 200 and shown.get_json()["chosen_center"] == CENTER_INSIDE
        for layer in ("plan.png", "audit.png"):
            response = client.get(f"/api/drill-plans/{saved['id']}/{layer}")
            assert response.status_code == 200 and response.mimetype == "image/png"
        # Creating a plan through the HTTP boundary exercises full validation.
        created = client.post(f"/api/specimens/{tile['id']}/drill-plans",
                              json=plan_payload([CENTER_INSIDE, CENTER_EDGE], "via http"))
        assert created.status_code == 201, created.get_data(as_text=True)
        new_id = created.get_json()["id"]
        audited = client.post(f"/api/drill-plans/{new_id}/audit", json=audit_payload)
        assert audited.status_code == 200, audited.get_data(as_text=True)
        audited_body = audited.get_json()
        assert isinstance(audited_body["audit"]["metrics"]["uncut_inside_circle_percent"], (int, float))
        assert audited_body["audit"]["metrics"]["units"] == "mm²"
        # A second audit on the same plan is refused rather than silently overwritten.
        duplicate = client.post(f"/api/drill-plans/{new_id}/audit", json=audit_payload)
        assert duplicate.status_code == 409
        print("HTTP routes: plan, overlays and audit all served correctly")

    print("all drill workflow checks passed")


def _png(image):
    stream = io.BytesIO()
    image.save(stream, format="PNG")
    return stream.getvalue()


if __name__ == "__main__":
    main()
